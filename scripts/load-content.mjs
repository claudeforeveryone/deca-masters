// Turns content/*.json (the source with answer keys) into idempotent SQL that loads DECA's content tables in project
// uhgzeuvybyohdbfuhfil: deca_events, deca_exams + deca_questions, deca_vocab_decks + deca_vocab_terms and
// deca_roleplay_events. Run the output with the Supabase MCP execute_sql tool (or psql). Answers live only in
// deca_questions; public/content never carries them (scripts/build-content.mjs).
//
//   node scripts/load-content.mjs                      every file under content/, sync on (see below)
//   node scripts/load-content.mjs <file.json> [...]    just those files (events.json first if role plays need it)
//   --dir <folder>      read a different content folder (for example tests/fixtures/content)
//   --no-sync           never retire anything (default for explicit files)
//   --sync              retire repo-loaded items that a file no longer lists (default for a whole folder)
//   --dry-run           end with ROLLBACK instead of COMMIT: shows what would change, changes nothing
//   --split <folder>    write one .sql file per content file (each its own transaction) instead of stdout
//
// The content is validated with content/validate.mjs first and nothing is written when it fails. The database
// validates again (deca_private.deca_load_*), so a hand-edited SQL file cannot load invalid content either.
// Every statement is an upsert keyed on ids, so running the same output twice changes nothing the second time.
// "Retire" means retired_at is set: the question stops being served and graded in new runs, but old runs and
// reviews keep it. Owner-imported items (origin owner_import) are never retired by a repo load.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { kindOf, loadCorpus, validateCorpus } from "../content/check.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const ORDER = ["events", "exam", "vocab", "roleplay"];

/** A standard SQL string literal (standard_conforming_strings is on in Supabase). */
export function sqlString(text) {
  if (text.includes("\u0000"))
    throw new Error("content contains a NUL character");
  return `'${text.replace(/'/g, "''")}'`;
}

/** The loader call for one validated document, or null for kinds that are not loaded (official-samples.json). */
export function loaderCall(kind, doc, { sync }) {
  const json = `${sqlString(JSON.stringify(doc))}::jsonb`;
  const s = sync ? "true" : "false";
  switch (kind) {
    case "events":
      return `deca_private.deca_load_events(${json}, ${s})`;
    case "exam":
      return `deca_private.deca_load_exam(${json}, 'repo', ${s})`;
    case "vocab":
      return `deca_private.deca_load_vocab(${json}, 'repo', ${s})`;
    case "roleplay":
      return `deca_private.deca_load_roleplays(${json}, ${s})`;
    default:
      return null;
  }
}

/**
 * Loader statements for a set of { path, doc } entries, events first (role plays check against them), then exams,
 * vocab and role plays, each group in path order. Throws when the content is invalid.
 */
export function loadStatements(entries, { sync = false } = {}) {
  const errors = validateCorpus(entries);
  if (errors.length)
    throw new Error(
      `content is invalid, nothing generated:\n- ${errors.join("\n- ")}`,
    );
  return entries
    .map((e) => ({ ...e, kind: kindOf(e.doc, e.path) }))
    .filter((e) => ORDER.includes(e.kind))
    .sort(
      (a, b) =>
        ORDER.indexOf(a.kind) - ORDER.indexOf(b.kind) ||
        a.path.localeCompare(b.path),
    )
    .map((e) => ({
      path: e.path,
      kind: e.kind,
      sql:
        `insert into deca_load_result (path, result) select ${sqlString(e.path)}, ` +
        `${loaderCall(e.kind, e.doc, { sync })};`,
    }));
}

/** One transaction that runs the statements and ends with a summary row (what execute_sql shows). */
export function wrapTransaction(
  statements,
  { dryRun = false, label = "content" } = {},
) {
  return [
    `-- DECA content load (${label}), generated by scripts/load-content.mjs. ${dryRun ? "DRY RUN: rolled back." : ""}`.trim(),
    "begin;",
    "create temp table deca_load_result (n serial, path text, result jsonb) on commit drop;",
    ...statements.map((s) => s.sql),
    "select jsonb_agg(jsonb_build_object('path', path) || result order by n) as loaded from deca_load_result;",
    dryRun ? "rollback;" : "commit;",
    "",
  ].join("\n");
}

function readEntry(file, contentDir) {
  const full = resolve(file);
  const rel = relative(contentDir, full);
  const path = rel.startsWith("..")
    ? full.split(sep).slice(-2).join("/")
    : rel.split(sep).join("/");
  try {
    return { path, doc: JSON.parse(readFileSync(full, "utf8")) };
  } catch (err) {
    return { path, doc: null, parseError: err.message };
  }
}

function parseArgs(argv) {
  const opts = {
    dir: join(root, "content"),
    files: [],
    sync: null,
    dryRun: false,
    split: null,
  };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--dir") opts.dir = resolve(argv[++i]);
    else if (a === "--sync") opts.sync = true;
    else if (a === "--no-sync") opts.sync = false;
    else if (a === "--dry-run") opts.dryRun = true;
    else if (a === "--split") opts.split = resolve(argv[++i]);
    else if (a.startsWith("--")) throw new Error(`unknown option ${a}`);
    else opts.files.push(a);
  }
  return opts;
}

const isMain = () =>
  process.argv[1] !== undefined &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href;

if (isMain()) {
  const opts = parseArgs(process.argv.slice(2));
  const entries = opts.files.length
    ? opts.files.map((f) => readEntry(f, opts.dir))
    : loadCorpus(opts.dir);
  const sync = opts.sync ?? opts.files.length === 0;
  const statements = loadStatements(entries, { sync });
  if (statements.length === 0) {
    console.error(
      "nothing to load (no events, exam, vocab or role-play files)",
    );
    process.exit(1);
  }
  if (opts.split) {
    mkdirSync(opts.split, { recursive: true });
    statements.forEach((s, i) => {
      const name = `${String(i + 1).padStart(2, "0")}-${s.path.replace(/[\\/]/g, "_")}.sql`;
      writeFileSync(
        join(opts.split, name),
        wrapTransaction([s], { dryRun: opts.dryRun, label: s.path }),
      );
    });
    console.error(
      `wrote ${statements.length} file(s) to ${opts.split} (sync ${sync ? "on" : "off"})`,
    );
  } else {
    process.stdout.write(
      wrapTransaction(statements, {
        dryRun: opts.dryRun,
        label: `sync ${sync ? "on" : "off"}`,
      }),
    );
  }
}
